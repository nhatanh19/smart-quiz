"""Pydantic schemas for Auto-Grading Engine and AI Tutor & Analytics module."""

from datetime import datetime, timezone
from typing import List, Optional
import uuid
from pydantic import BaseModel, ConfigDict, Field
from app.models.entities import QuestionType
from app.schemas.common import QuestionOptionSchema


# ==============================================================================
# ISSUE #14: AUTO-GRADING ENGINE SCHEMAS
# ==============================================================================


class AnswerGradingSchema(BaseModel):
    """Grading detail for a single question."""

    question_id: uuid.UUID
    is_correct: bool
    points_awarded: float

    model_config = ConfigDict(from_attributes=True)


class GradingResultSchema(BaseModel):
    """Overall grading result for an exam attempt."""

    attempt_id: uuid.UUID
    score: float
    correct_count: int
    total_questions: int
    answers: List[AnswerGradingSchema]
    time_spent_seconds: int
    already_graded: bool = False

    model_config = ConfigDict(from_attributes=True)


# ==============================================================================
# ISSUE #16: AI TUTOR CONTEXTUAL EXPLANATION SCHEMAS
# ==============================================================================


class AITutorFeedbackSchema(BaseModel):
    """Structured feedback generated by AI Tutor.

    Synchronized 100% with docs/DATABASE_GUIDE.md section 5.5:
    attempt_answers.ai_tutor_feedback JSONB schema.
    """

    version: int = Field(default=1, description="Version of the feedback schema")
    explanation: str = Field(
        description="Giải thích cặn kẽ tại sao phương án chuẩn là đáp án đúng (bản chất kiến thức)."
    )
    why_selected_wrong: str = Field(
        description="Phân tích cặn kẽ, trúng nguyên nhân nhầm lẫn: vì sao phương án sinh viên chọn là sai."
    )
    study_suggestions: List[str] = Field(
        default_factory=list,
        description="Danh sách 2-3 chủ đề hoặc tài liệu gợi ý ôn tập khắc phục lỗ hổng kiến thức.",
    )
    model: str = Field(default="gpt-4o-mini", description="Mô hình AI thực hiện phân tích")
    generated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Thời điểm sinh phản hồi (ISO 8601)",
    )


class AITutorExplanationRequest(BaseModel):
    """Payload to request an AI Tutor explanation for a question answer."""

    # Option 1: Database-backed lookup
    attempt_id: Optional[uuid.UUID] = Field(
        default=None, description="UUID of the exam attempt (exam_attempts.id)"
    )
    question_id: Optional[uuid.UUID] = Field(
        default=None, description="UUID of the question (questions.id)"
    )

    # Option 2: Direct question context (for on-demand / review testing)
    question_content: Optional[str] = Field(
        default=None, description="Nội dung câu hỏi trắc nghiệm"
    )
    question_type: Optional[QuestionType] = Field(
        default=QuestionType.SINGLE_CHOICE, description="Loại câu hỏi"
    )
    options: Optional[List[QuestionOptionSchema]] = Field(
        default=None, description="Danh sách các phương án lựa chọn"
    )
    selected_options: Optional[List[str]] = Field(
        default_factory=list, description="Danh sách ID phương án thí sinh đã chọn (ví dụ: ['B'])"
    )
    correct_options: Optional[List[str]] = Field(
        default_factory=list, description="Danh sách ID phương án đúng (ví dụ: ['A'])"
    )
    question_explanation: Optional[str] = Field(
        default=None, description="Lời giải thích gốc đi kèm câu hỏi trong ngân hàng đề"
    )


class AITutorExplanationData(BaseModel):
    """Response payload enclosing the feedback and execution metrics."""

    attempt_id: Optional[uuid.UUID] = None
    question_id: Optional[uuid.UUID] = None
    is_correct: Optional[bool] = None
    selected_options: List[str] = Field(default_factory=list)
    correct_options: List[str] = Field(default_factory=list)
    feedback: AITutorFeedbackSchema
    cached: bool = Field(default=False, description="Whether feedback was retrieved from cache/DB")
    response_time_ms: float = Field(
        description="Thời gian xử lý tính bằng mili-giây (DoD: < 3000 ms)"
    )


# ==============================================================================
# ISSUE #15: POST-EXAM DETAILED REVIEW MODE SCHEMAS (WBS 5.1.2)
# ==============================================================================


class QuestionReviewOptionSchema(BaseModel):
    """Option details including standard correct key flag."""

    id: str
    text: str
    is_correct: bool = False


class QuestionReviewItemSchema(BaseModel):
    """Detailed question review item for a student's submitted exam attempt."""

    question_id: uuid.UUID
    content: str
    question_type: str
    cognitive_level: str
    options: List[QuestionReviewOptionSchema]
    selected_options: List[str]
    correct_options: List[str]
    is_correct: bool
    points_awarded: float
    explanation: Optional[str] = None
    ai_tutor_feedback: Optional[dict] = None
    order_index: int = 1


class ExamReviewResponseSchema(BaseModel):
    """Top-level review mode payload for an exam attempt."""

    attempt_id: uuid.UUID
    exam_id: uuid.UUID
    exam_title: str
    student_id: uuid.UUID
    student_name: Optional[str] = None
    score: Optional[float] = None
    max_score: float = 10.0
    status: str
    started_at: Optional[str] = None
    submitted_at: Optional[str] = None
    time_spent_seconds: int = 0
    total_questions: int
    correct_count: int
    incorrect_count: int
    questions_review: List[QuestionReviewItemSchema]


# ==============================================================================
# ISSUE #17: KNOWLEDGE GAP DIAGNOSTIC SCHEMAS (WBS 5.2.2)
# ==============================================================================


class WeakTopicItemSchema(BaseModel):
    """Aggregated weak topic diagnostic entry."""

    topic: str
    wrong_count: int
    total_questions: int
    accuracy_percentage: float
    question_ids: List[str]
    cognitive_levels: List[str] = Field(default_factory=list)


class ActionableStudyAdviceSchema(BaseModel):
    """Actionable recommendation for improving performance in weak areas."""

    title: str
    description: str
    action_type: str = "PRACTICE_QUIZ"
    priority: str = "HIGH"
    resource_hint: Optional[str] = None


class KnowledgeGapDiagnosticResponse(BaseModel):
    """Knowledge Gap Diagnostic Card response schema."""

    attempt_id: uuid.UUID
    exam_id: uuid.UUID
    summary_headline: str
    primary_weak_topic: Optional[str] = None
    has_gaps: bool
    total_wrong: int
    total_questions: int
    weak_topics: List[WeakTopicItemSchema]
    advice: List[ActionableStudyAdviceSchema]
    generated_at: str
